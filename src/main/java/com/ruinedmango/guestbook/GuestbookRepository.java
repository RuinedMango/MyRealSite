package com.ruinedmango.guestbook;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.*;
import java.time.Instant;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

public final class GuestbookRepository {
    private static final Logger LOGGER = LoggerFactory.getLogger(GuestbookRepository.class);
    private static final String DEFAULT_URL = "jdbc:h2:file:./data/guestbook";
    private static final int MAX_ENTRIES = 100;

    private final String jdbcUrl;

    public GuestbookRepository(String jdbcUrl) {
        this.jdbcUrl = jdbcUrl;
    }

    public static GuestbookRepository fromEnvironment() {
        String configured = System.getenv("GUESTBOOK_DB");
        if (configured != null && !configured.isBlank()) {
            return new GuestbookRepository(configured.trim());
        }

        try {
            Files.createDirectories(Path.of("data"));
        } catch (IOException e) {
            throw new UncheckedIOException("Could not create the data directory", e);
        }
        return new GuestbookRepository(DEFAULT_URL);
    }
    
    public static GuestbookRepository inMemory() {
        return new GuestbookRepository("jdbc:h2:mem:guestbook-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
    }

    public void initialize() {
        String sql = """
                CREATE TABLE IF NOT EXISTS guestbook_entries (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(50) NOT NULL,
                    message VARCHAR(500) NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """;

        try (Connection connection = connect(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
            LOGGER.info("Guestbook database ready");
        } catch (SQLException e) {
            throw new IllegalStateException("Could not initialize the guestbook database", e);
        }
    }

    public GuestbookEntry add(String name, String message) {
        String sql = "INSERT INTO guestbook_entries (name, message, created_at) VALUES (?, ?, ?)";
        Instant createdAt = Instant.now();

        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, name);
            statement.setString(2, message);
            statement.setObject(3, createdAt.atOffset(ZoneOffset.UTC));
            statement.executeUpdate();

            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (!keys.next()) {
                    throw new SQLException("Insert did not return an id");
                }
                return new GuestbookEntry(keys.getLong(1), name, message, createdAt);
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Could not add a guestbook entry", e);
        }
    }

    public List<GuestbookEntry> recent() {
        String sql = """
                SELECT id, name, message, created_at
                FROM guestbook_entries
                ORDER BY created_at DESC, id DESC
                LIMIT ?
                """;

        List<GuestbookEntry> entries = new ArrayList<>();
        try (Connection connection = connect(); PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, MAX_ENTRIES);
            try (ResultSet results = statement.executeQuery()) {
                while (results.next()) {
                    entries.add(new GuestbookEntry(
                            results.getLong("id"),
                            results.getString("name"),
                            results.getString("message"),
                            results.getObject("created_at", OffsetDateTime.class).toInstant()
                    ));
                }
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Could not read guestbook entries", e);
        }
        return entries;
    }

    private Connection connect() throws SQLException {
        return DriverManager.getConnection(jdbcUrl);
    }
}
